export const DEPARTMENT_SET = new Set(ALL_DEPARTMENTS);

export function normalizeDepartmentSelection(value, fallback = DEFAULT_DEPARTMENTS) {
  const input = Array.isArray(value) ? value : [];
  const selected = [];
  const seen = new Set();

  for (const item of input) {
    const department = String(item || "").trim();
    if (!DEPARTMENT_SET.has(department) || seen.has(department)) continue;
    seen.add(department);
    selected.push(department);
  }

  return selected.length ? selected : [...fallback];
}
